"""Online Fano-slate selector using Bayesian change-point hit-rate experts.

Each source slate is generated by a prior-only Fano v7 experiment. An expert's
weight for a target is its prequential Beta-Bernoulli change-point predictive
probability of an exact hit, learned only from that expert's earlier outcomes.
The current target is scored before any expert state is updated.

This is exploratory: its source library was curated after reviewing the same
759 outcomes, so a historical score is not independent validation.
"""
from __future__ import annotations

from datetime import datetime
import hashlib
import json
import math
from pathlib import Path
import re
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import astra

DRAW_COUNT = 759
EXPECTED_FINGERPRINT = "c7d1cd0199ee945a9102dab341c7353cf0c76272b05d69bee3b6119d0bed6145"
STAGE_CUTOFF = 49
TICKET_COUNT = 5
NUMBER_SPACE = 1_000_000
CHANGE_HAZARD = 1.0 / 120.0
PRIOR_STRENGTH = 759.0
PRIOR_HIT_RATE = TICKET_COUNT / NUMBER_SPACE
PRIOR_ALPHA = PRIOR_STRENGTH * PRIOR_HIT_RATE
PRIOR_BETA = PRIOR_STRENGTH * (1.0 - PRIOR_HIT_RATE)
MINIMUM_HITS = 10


def _load_draws_and_fingerprint():
    dated = []
    for row in astra.load_existing_astra_history():
        values = astra._category_values(row, "prize1", 6)
        if values is not None:
            dated.append((astra._history_date(row["date"]), values[0]))
    dated.sort()
    if len(dated) != DRAW_COUNT:
        raise RuntimeError(f"Expected {DRAW_COUNT} valid prize1 draws, got {len(dated)}")
    material = "\n".join(f"{day.isoformat()}|{number}" for day, number in dated).encode("ascii")
    fingerprint = hashlib.sha256(material).hexdigest()
    if fingerprint != EXPECTED_FINGERPRINT:
        raise RuntimeError(f"Dataset fingerprint changed: {fingerprint}")
    return dated, fingerprint


def _load_source_reports():
    folder = ROOT / ".scratch" / "fano-v7-walk-forward"
    reports = []
    for path in sorted(folder.glob("results-2026-10-15-stage-*.json")):
        match = re.search(r"stage-(\d+)-", path.name)
        if match is None:
            continue
        stage = int(match.group(1))
        if stage > STAGE_CUTOFF:
            continue
        report = json.loads(path.read_text(encoding="utf-8"))
        forecasts = report.get("v7", {}).get("forecasts")
        if report.get("actuals_sha256") != EXPECTED_FINGERPRINT:
            raise RuntimeError(f"Fingerprint mismatch in {path.name}")
        if not isinstance(forecasts, list) or len(forecasts) != DRAW_COUNT:
            raise RuntimeError(f"Expected {DRAW_COUNT} forecasts in {path.name}")
        for index, row in enumerate(forecasts):
            candidates = row.get("candidates")
            prior_count = row.get("prior_valid_draws", row.get("prior_draws"))
            if prior_count != index:
                raise RuntimeError(f"Prior count mismatch in {path.name} at {index}")
            if (not isinstance(candidates, list) or len(candidates) != TICKET_COUNT
                    or len(set(candidates)) != TICKET_COUNT
                    or any(not isinstance(n, str) or len(n) != 6
                           or not n.isascii() or not n.isdigit() for n in candidates)):
                raise RuntimeError(f"Invalid five-number slate in {path.name} at {index}")
        reports.append({"stage": stage, "file": path.name, "forecasts": forecasts})
    reports.sort(key=lambda report: report["stage"])
    if len(reports) != STAGE_CUTOFF or [r["stage"] for r in reports] != list(range(1, STAGE_CUTOFF + 1)):
        raise RuntimeError(f"Expected Stage 1-{STAGE_CUTOFF}; found {[r['stage'] for r in reports]}")
    reference_dates = [row["target_date"] for row in reports[0]["forecasts"]]
    reference_actuals = [row["actual"] for row in reports[0]["forecasts"]]
    for report in reports:
        if [row["target_date"] for row in report["forecasts"]] != reference_dates:
            raise RuntimeError(f"Target dates differ in {report['file']}")
        if [row["actual"] for row in report["forecasts"]] != reference_actuals:
            raise RuntimeError(f"Actuals differ in {report['file']}")
    return reports


def _predictive_hit_probability(states):
    """Average Beta-Bernoulli predictive probability over BOCPD run lengths."""
    return sum(mass * alpha / (alpha + beta)
               for mass, alpha, beta in states)


def _update_change_point(states, hit):
    """Update run-length posterior after one observed expert hit/miss."""
    y = int(hit)
    evidence = sum(
        mass * ((alpha / (alpha + beta)) if y else (beta / (alpha + beta)))
        for mass, alpha, beta in states
    )
    if evidence <= 0.0:
        raise RuntimeError("BOCPD evidence underflowed")
    updated = [(CHANGE_HAZARD, PRIOR_ALPHA + y, PRIOR_BETA + 1 - y)]
    growth = 1.0 - CHANGE_HAZARD
    for mass, alpha, beta in states:
        prediction = alpha / (alpha + beta)
        likelihood = prediction if y else 1.0 - prediction
        new_mass = mass * growth * likelihood / evidence
        if new_mass > 1e-15:
            updated.append((new_mass, alpha + y, beta + 1 - y))
    total = sum(mass for mass, _, _ in updated)
    return [(mass / total, alpha, beta) for mass, alpha, beta in updated]


def _audit_stage_reports(run_date, dated, fingerprint, current_report):
    """Strictly recheck every saved stage report against the immutable draws."""
    folder = ROOT / ".scratch" / "fano-v7-walk-forward"
    reports = {50: ("current-run", current_report)}
    for path in folder.glob(f"results-{run_date}-stage-*.json"):
        match = re.search(r"stage-(\d+)-", path.name)
        if match is None:
            continue
        stage = int(match.group(1))
        if stage == 50:
            continue
        if stage in reports:
            raise RuntimeError(f"Duplicate saved Stage {stage} report")
        reports[stage] = (path.name, json.loads(path.read_text(encoding="utf-8")))

    stages = sorted(reports)
    if stages != list(range(1, stages[-1] + 1)):
        raise RuntimeError(f"Stage reports are not contiguous: {stages}")
    expected_dates = [day.isoformat() for day, _ in dated]
    expected_actuals = [number for _, number in dated]
    total_forecasts = 0
    stage_hit_counts = {}

    for stage in stages:
        name, report = reports[stage]
        if report.get("actuals_sha256") != fingerprint:
            raise RuntimeError(f"Fingerprint mismatch in Stage {stage}: {name}")
        forecasts = report.get("v7", {}).get("forecasts")
        if not isinstance(forecasts, list) or len(forecasts) != DRAW_COUNT:
            raise RuntimeError(f"Stage {stage} must contain exactly {DRAW_COUNT} forecasts")
        if [row.get("target_date") for row in forecasts] != expected_dates:
            raise RuntimeError(f"Chronology mismatch in Stage {stage}: {name}")

        recomputed_hits = 0
        for index, (row, actual) in enumerate(zip(forecasts, expected_actuals)):
            if row.get("actual") != actual:
                raise RuntimeError(f"Actual mismatch in Stage {stage} at draw {index}")
            prior_count = row.get("prior_valid_draws", row.get("prior_draws"))
            if prior_count != index:
                raise RuntimeError(f"Prior-count mismatch in Stage {stage} at draw {index}")
            candidates = row.get("candidates")
            if (not isinstance(candidates, list) or len(candidates) != TICKET_COUNT
                    or len(set(candidates)) != TICKET_COUNT
                    or any(not isinstance(value, str) or len(value) != 6
                           or not value.isascii() or not value.isdigit()
                           for value in candidates)):
                raise RuntimeError(f"Invalid candidate slate in Stage {stage} at draw {index}")
            hit = actual in candidates
            if "hit" in row and row["hit"] is not hit:
                raise RuntimeError(f"Hit flag mismatch in Stage {stage} at draw {index}")
            recomputed_hits += int(hit)

        if report["v7"].get("hits") != recomputed_hits:
            raise RuntimeError(f"Recomputed hit count differs in Stage {stage}: {name}")
        saved_hit_dates = report["v7"].get("hit_dates")
        if saved_hit_dates is not None:
            computed_hit_dates = [row["target_date"] for row in forecasts
                                  if row["actual"] in row["candidates"]]
            if saved_hit_dates != computed_hit_dates:
                raise RuntimeError(f"Hit-date list differs in Stage {stage}: {name}")
        total_forecasts += len(forecasts)
        stage_hit_counts[str(stage)] = recomputed_hits

    return {"stages": stages, "stage_count": len(stages),
            "forecasts_checked": total_forecasts,
            "draw_count_each_stage": DRAW_COUNT,
            "prior_counts_0_to_758_each_stage": True,
            "five_distinct_six_digit_candidates_each_stage": True,
            "hit_counts_recomputed": stage_hit_counts}


def run():
    started = time.perf_counter()
    dated, fingerprint = _load_draws_and_fingerprint()
    reports = _load_source_reports()
    source_count = len(reports)
    states = [[(1.0, PRIOR_ALPHA, PRIOR_BETA)] for _ in reports]
    hits = 0
    hit_dates = []
    forecasts = []

    for target_index, (target_date, actual) in enumerate(dated):
        source_rows = [report["forecasts"][target_index] for report in reports]
        if any(row["target_date"] != target_date.isoformat() or row["actual"] != actual
               for row in source_rows):
            raise RuntimeError(f"Source forecast alignment failed at index {target_index}")

        # The weights are computed only from each expert's earlier scored draws.
        hit_propensities = [_predictive_hit_probability(state) for state in states]
        total_propensity = sum(hit_propensities)
        if total_propensity <= 0.0:
            raise RuntimeError("No positive expert predictive mass")
        expert_weights = [p / total_propensity for p in hit_propensities]

        # Fano source slates vote with their prior online hit-rate weight.
        candidate_scores = {}
        for expert_index, row in enumerate(source_rows):
            weight = expert_weights[expert_index]
            for number in row["candidates"]:
                candidate_scores[number] = candidate_scores.get(number, 0.0) + weight / TICKET_COUNT
        selected = sorted(candidate_scores, key=lambda n: (-candidate_scores[n], n))[:TICKET_COUNT]
        if len(selected) != TICKET_COUNT or len(set(selected)) != TICKET_COUNT:
            raise RuntimeError("Adaptive Fano slate must have five distinct numbers")

        hit = actual in selected
        hits += int(hit)
        if hit:
            hit_dates.append(target_date.isoformat())
        forecasts.append({
            "target_date": target_date.isoformat(),
            "prior_valid_draws": target_index,
            "actual": actual,
            "candidates": selected,
            "hit": hit,
            "prior_expert_hit_count": sum(int(actual in row["candidates"]) for row in source_rows),
            "top_expert_weights_before_target": sorted(
                ((reports[i]["file"], expert_weights[i], hit_propensities[i])
                 for i in range(source_count)), key=lambda item: -item[1])[:8],
        })

        # Update only after this target has been predicted and scored.
        for expert_index, row in enumerate(source_rows):
            states[expert_index] = _update_change_point(
                states[expert_index], actual in row["candidates"])
        if (target_index + 1) % 100 == 0:
            print(f"walk-forward: {target_index + 1}/{DRAW_COUNT}, hits={hits}", flush=True)

    recomputed_hits = sum(row["actual"] in row["candidates"] for row in forecasts)
    if recomputed_hits != hits:
        raise RuntimeError("Reported hit count does not match candidate lists")
    if len(forecasts) != DRAW_COUNT or [row["prior_valid_draws"] for row in forecasts] != list(range(DRAW_COUNT)):
        raise RuntimeError("Output chronology audit failed")
    if any(len(row["candidates"]) != TICKET_COUNT or len(set(row["candidates"])) != TICKET_COUNT
           for row in forecasts):
        raise RuntimeError("Output five-distinct-candidates audit failed")

    run_date = datetime.now(astra.THAILAND_TZ).date().isoformat()
    report = {
        "run_date": run_date,
        "draw_count": DRAW_COUNT,
        "date_range": [dated[0][0].isoformat(), dated[-1][0].isoformat()],
        "actuals_sha256": fingerprint,
        "target": "at least 10 exact six-digit first-prize hits in 759 walk-forward targets, with exactly five distinct candidates per target",
        "walk_forward": "expert weights use Bayesian online change-point predictions from earlier exact-hit/miss outcomes; current draw is scored before all expert states update",
        "model_family": "adaptive Fano slate portfolio weighted by expert-specific Beta-Bernoulli Bayesian online change-point hit-rate predictions",
        "source_expert_count": source_count,
        "source_files": [report["file"] for report in reports],
        "change_hazard": CHANGE_HAZARD,
        "beta_prior": {"alpha": PRIOR_ALPHA, "beta": PRIOR_BETA,
                       "prior_mean_exact_hit_rate": PRIOR_HIT_RATE,
                       "prior_strength_draws": PRIOR_STRENGTH},
        "uniform_expected_hits": DRAW_COUNT * TICKET_COUNT / NUMBER_SPACE,
        "v7": {"hits": hits, "hit_rate_percent": round(100 * hits / DRAW_COUNT, 8),
               "hit_dates": hit_dates, "forecasts": forecasts},
        "threshold": {"minimum_hits": MINIMUM_HITS, "met": hits >= MINIMUM_HITS},
        "validation": {"forecast_count": len(forecasts), "prior_counts_0_to_758": True,
                       "five_distinct_candidates_each": True,
                       "recomputed_hits": recomputed_hits,
                       "all_source_fingerprints_match": True},
        "interpretation": "historical exploratory evaluation only. The 49-source slate library was assembled after reviewing these same outcomes; this score is not independent validation and does not establish better odds",
        "elapsed_seconds": round(time.perf_counter() - started, 3),
    }
    all_stage_audit = _audit_stage_reports(run_date, dated, fingerprint, report)
    report["validation"]["all_saved_stage_reports"] = all_stage_audit
    output = ROOT / ".scratch" / "fano-v7-walk-forward" / f"results-{run_date}-stage-50-hit-bocpd-meta.json"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({"hits": hits, "hit_rate_percent": report["v7"]["hit_rate_percent"],
                      "minimum_hits": MINIMUM_HITS, "met": hits >= MINIMUM_HITS,
                      "hit_dates": hit_dates, "source_expert_count": source_count,
                      "all_saved_stage_reports": all_stage_audit,
                      "data_fingerprint": fingerprint, "result_file": str(output),
                      "elapsed_seconds": report["elapsed_seconds"]},
                     ensure_ascii=False), flush=True)


if __name__ == "__main__":
    run()
